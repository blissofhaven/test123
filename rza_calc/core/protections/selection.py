# -*- coding: utf-8 -*-
"""Детерминированный выбор определяющего режима.

Зачем это отдельный модуль
--------------------------
Уставка и коэффициент чувствительности выбираются по экстремуму тока среди
режимов. В радиальной сети ток фидера часто **не зависит** от состояния
удалённой подстанции, поэтому несколько режимов дают физически один и тот же
ток. Различие между ними — только шум обращения матрицы узловых
проводимостей, порядка одного-двух последних битов.

Строгое сравнение (``i > best``) превращает этот шум в категорическое
утверждение: «уставку определил режим ремонта Т1 Северной». Утверждение
ложное — её одинаково определили все пять режимов, а конкретный победитель
зависит от сборки BLAS на машине. Один и тот же проект на двух компьютерах
давал разные имена определяющего режима при совпадающих до последнего знака
числах.

Правило
-------
Среди кандидатов, попадающих в полосу численного шума вокруг экстремума,
выбирается **первый по порядку объявления режимов в проекте**. Порядок
объявления задаёт человек, он воспроизводим и не зависит от машины.

Полоса ``RELATIVE_BAND`` задана до измерений и обоснована так же, как допуск
эталона расчётных чисел: накопленная ошибка обращения матрицы имеет порядок
``eps_double · cond(Y)`` ≈ 1e-11…1e-13 относительной величины, а физически
значимое различие режимов — не менее 1e-6. Полоса 1e-9 лежит между ними.
Подбирать её под полученный результат запрещено правилами карты.
"""
from __future__ import annotations

from typing import Callable, Iterable, Sequence, TypeVar

#: Полоса, внутри которой два режима считаются давшими один и тот же ток.
RELATIVE_BAND = 1e-9
#: Абсолютная полоса для величин вблизи нуля (А).
ABSOLUTE_BAND = 1e-9

T = TypeVar("T")


def _within_band(value: float, extremum: float) -> bool:
    scale = abs(extremum)
    return abs(value - extremum) <= max(RELATIVE_BAND * scale, ABSOLUTE_BAND)


def pick_extreme(
    candidates: Sequence[T],
    key: Callable[[T], float],
    *,
    largest: bool,
) -> tuple[T | None, int]:
    """Вернуть определяющего кандидата и число кандидатов, равных ему.

    ``candidates`` обязан идти в порядке объявления режимов в проекте: именно
    он разрешает равенство. Возвращается ``(кандидат, сколько_равных)``;
    ``сколько_равных == 1`` означает, что экстремум единственный и оговорка о
    равенстве режимов не нужна.

    Значение берётся у выбранного кандидата целиком — ток, решатель и доля
    тока остаются согласованными между собой. От истинного экстремума оно
    может отличаться не более чем на ``RELATIVE_BAND``, то есть на величину,
    которую нельзя наблюдать ни в одной выдаче программы.
    """
    rows = list(candidates)
    if not rows:
        return None, 0
    values = [float(key(row)) for row in rows]
    extremum = max(values) if largest else min(values)
    tied = [row for row, value in zip(rows, values) if _within_band(value, extremum)]
    return tied[0], len(tied)


def tie_note(count: int, chosen_name: str) -> str | None:
    """Оговорка для протокола, когда режимов с одинаковым током несколько.

    Возвращает ``None``, если равенства нет: молчание в этом случае честнее
    оговорки, которая ничего не добавляет.
    """
    if count <= 1:
        return None
    return (
        f"Ток одинаков в {count} режимах в пределах численной точности расчёта. "
        f"Определяющим принят первый по порядку объявления — «{chosen_name}»; "
        "выбор конкретного режима из равных не влияет на уставку."
    )


def iter_in_declaration_order(net, modes: Iterable) -> list:
    """Упорядочить режимы так, как они объявлены в проекте.

    ``modes_where_active()`` уже возвращает их в этом порядке, но полагаться
    на это неявно нельзя: порядок — часть правила выбора, а не совпадение.
    """
    order = {mode_id: index for index, mode_id in enumerate(net.modes)}
    return sorted(modes, key=lambda md: order.get(getattr(md, "id", None), 1 << 30))
